import { makeDedupeKey, type Opportunity } from "../domain/opportunity"

/**
 * 只收录来源页写明的事实。
 * 来源没写的字段留空，不补公司、城市、岗位或截止日期。
 * 原文只写到“某日”而没有钟点的，截止收到当天 23:59（北京时间），并在 summary 里说明。
 * 宣讲转载页没有网申截止，deadline_at 用宣讲开始时间，source_tier 为 unverified。
 */

const TALKS_URL = "https://ezhizhaopin.com/school.php?id=2233&section=lectures"

function withKey(
  item: Omit<Opportunity, "dedupe_key" | "fetched_at" | "work_location" | "responsibilities" | "requirements" | "major_requirements" | "major_tags"> &
    Partial<Pick<Opportunity, "fetched_at" | "work_location" | "responsibilities" | "requirements" | "major_requirements" | "major_tags">>,
): Opportunity {
  return {
    fetched_at: item.fetched_at ?? item.updated_at,
    work_location: item.work_location ?? "未提供",
    responsibilities: item.responsibilities ?? "未提供",
    requirements: item.requirements ?? "未提供",
    major_requirements: item.major_requirements ?? "未提供",
    major_tags: item.major_tags ?? ["通用"],
    ...item,
    dedupe_key: makeDedupeKey(item.company, item.title, item.deadline_at),
  }
}

function talk(input: {
  id: string
  title: string
  company: string
  location: string
  deadline_at: string
  whenText: string
}): Opportunity {
  return withKey({
    id: input.id,
    title: input.title,
    kind: "campus_recruit",
    company: input.company,
    role_tags: [],
    location: input.location,
    deadline_at: input.deadline_at,
    source_url: TALKS_URL,
    source_name: "E职科技",
    source_tier: "unverified",
    apply_url: "",
    summary: `E职科技「成都理工大学近期宣讲会安排」收录：${input.whenText}，${input.location}。该页未给出岗位、网申截止日期和投递链接，因此 deadline_at 取宣讲开始时间，来源层级为未核验。具体安排以学校通知为准。`,
    status: "active",
    published_at: "",
    updated_at: "",
  })
}

